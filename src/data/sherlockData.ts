// Алгоритм TextPaginator с переносом строго по границам слов и LRU-кешированием
const paginationCache = new Map<string, PageModel[]>();

export function paginateChapterText(
  chapterId: number,
  content: string,
  widthPx: number,
  heightPx: number,
  fontSizeSp: number
): PageModel[] {
  const safeWidth = Math.max(260, widthPx);
  const safeHeight = Math.max(240, heightPx);
  const lineHeightPx = fontSizeSp * 1.55;
  const cacheKey = `${chapterId}_${safeWidth}_${safeHeight}_${fontSizeSp}`;

  const cached = paginationCache.get(cacheKey);
  if (cached) return cached;

  const avgCharWidthPx = fontSizeSp * 0.58;
  const charsPerLine = Math.max(22, Math.floor(safeWidth / avgCharWidthPx));
  const maxLinesPerPage = Math.max(5, Math.floor(safeHeight / lineHeightPx));

  const pages: PageModel[] = [];
  const totalLength = content.length;
  let currentStartOffset = 0;
  let pageIndex = 0;

  while (currentStartOffset < totalLength) {
    while (
      currentStartOffset < totalLength &&
      (content[currentStartOffset] === ' ' ||
        content[currentStartOffset] === '\t' ||
        content[currentStartOffset] === '\n')
    ) {
      currentStartOffset++;
    }
    if (currentStartOffset >= totalLength) break;

    let cursor = currentStartOffset;
    let linesUsed = 0;
    let lastValidCut = currentStartOffset;

    while (cursor < totalLength && linesUsed < maxLinesPerPage) {
      const nextNewline = content.indexOf('\n', cursor);
      const maxLineEnd = Math.min(cursor + charsPerLine, totalLength);

      if (nextNewline !== -1 && nextNewline <= maxLineEnd) {
        const segmentLen = nextNewline - cursor;
        cursor = nextNewline + 1;
        // Empty line between paragraphs adds 0.75 line spacing; text line before newline adds 1 line
        linesUsed += segmentLen === 0 ? 0.75 : 1.0;
        lastValidCut = cursor;
      } else {
        let lineCut = maxLineEnd;
        if (lineCut < totalLength) {
          const charBefore = content[lineCut - 1];
          const charAt = content[lineCut];
          if (!/\s/.test(charBefore) && !/\s/.test(charAt)) {
            let back = lineCut - 1;
            while (back > cursor && !/\s/.test(content[back])) {
              back--;
            }
            if (back > cursor) {
              lineCut = back + 1;
            }
          }
        }
        cursor = lineCut;
        linesUsed += 1;
        lastValidCut = cursor;
      }
    }

    const finalEndOffset = Math.max(currentStartOffset + 1, Math.min(lastValidCut, totalLength));
    const pageText = content.slice(currentStartOffset, finalEndOffset).trimEnd();

    pages.push({
      pageIndex,
      startCharOffset: currentStartOffset,
      endCharOffset: finalEndOffset,
      text: pageText,
    });

    currentStartOffset = finalEndOffset;
    pageIndex++;
  }

  if (pages.length === 0) {
    pages.push({
      pageIndex: 0,
      startCharOffset: 0,
      endCharOffset: totalLength,
      text: content,
    });
  }

  paginationCache.set(cacheKey, pages);
  return pages;
}

export function findPageIndexForOffset(pages: PageModel[], charOffset: number): number {
  if (pages.length === 0) return 0;
  const clamped = Math.max(0, charOffset);
  if (clamped <= pages[0].startCharOffset) return 0;
  if (clamped >= pages[pages.length - 1].endCharOffset) return pages.length - 1;

  let low = 0;
  let high = pages.length - 1;
  while (low <= high) {
    const mid = (low + high) >>> 1;
    const p = pages[mid];
    if (clamped < p.startCharOffset) {
      high = mid - 1;
    } else if (clamped >= p.endCharOffset) {
      low = mid + 1;
    } else {
      return p.pageIndex;
    }
  }
  return Math.min(Math.max(0, low), pages.length - 1);
}

export function getOffsetForPage(pages: PageModel[], pageIndex: number): number {
  if (pages.length === 0) return 0;
  const safeIndex = Math.min(Math.max(0, pageIndex), pages.length - 1);
  return pages[safeIndex].startCharOffset;
}
